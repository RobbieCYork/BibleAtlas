/**
 * One image per lifespan biography (people with a bornYear), keyed by Person.id.
 *
 * Nobody knows what most biblical figures looked like, so for biblical, ancient and medieval
 * people these are ARTISTIC DEPICTIONS (paintings, icons, mosaics, engravings, coins, ancient
 * busts), captioned as such. Later figures get period portraits or, from the photographic era,
 * photographs. Never AI-generated; never a living person.
 *
 * Every image is self-hosted (public/people/<id>.webp, max 800px, lazy-loaded) and came from
 * Wikimedia Commons under a licence verified on the file's own page: public domain, PD-US,
 * PD-Art / PD-old, or CC0. Nothing under CC BY-SA, NC or ND. `verified` is the date the licence
 * was checked. A person absent from this map simply renders with no image.
 */
export interface PersonImage {
  /** Site-relative path of the self-hosted WebP. */
  src: string;
  width: number;
  height: number;
  alt: string;
  /** Honest caption: says it is a depiction, not a likeness, and names the work. */
  caption: string;
  /** Visible credit link text. */
  credit: string;
  /** Wikimedia Commons file page the licence was verified on. */
  sourceUrl: string;
  title: string;
  artist: string;
  date: string;
  license: string;
  /** Required attribution line (none is legally required for these licences; kept for the record). */
  attribution: string;
  /** ISO date the licence was verified on the file page. */
  verified: string;
}

