/** "Acts 13:4"-style label for a plan day, matching the format the chapter loader parses — the
 * loader only ever sees `book`/`chapter`/`verse`, so a multi-chapter `endChapter` must NOT be
 * included here; use `formatPlanDayDisplayReference` for the human-facing "Genesis 1-3" label. */
export function formatPlanDayReference(day: ReadingPlanDay): string {
  const { book, chapter, verse } = day.reference;
  return `${book} ${chapter}${verse ? `:${verse}` : ""}`;
}

/** Human-facing reference label for a plan day's day-list row — includes the `endChapter` range
 * when present (e.g. "Genesis 1-3"), unlike `formatPlanDayReference` which the chapter loader parses. */
export function formatPlanDayDisplayReference(day: ReadingPlanDay): string {
  const { book, chapter, endChapter, verse } = day.reference;
  if (endChapter && endChapter > chapter) return `${book} ${chapter}-${endChapter}`;
  return `${book} ${chapter}${verse ? `:${verse}` : ""}`;
}
